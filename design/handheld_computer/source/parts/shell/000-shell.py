import math
case_width = param('case_width',85.0)
case_depth = param('case_depth',115.0)
case_corner = param('case_corner',9.0)
case_top_center = param('case_top_center',30.0)
case_slope = param('case_slope',8.0)
shell_wall = param('shell_wall',2.4)
shell_lower_z = param('shell_lower_z',2.7)
shell_edge_radius = param('shell_edge_radius',1.0)
fascia_width = param('fascia_width',77.0)
fascia_depth = param('fascia_depth',65.0)
fascia_y = param('fascia_y',14.0)
fascia_radius = param('fascia_radius',6.0)
panel_gap = param('panel_gap',0.25)
button_x = param('button_x',26.0)
button_y = param('button_y',-37.0)
button_diameter = param('button_diameter',9.0)
rear_panel_width = param('rear_panel_width',65.0)
rear_panel_height = param('rear_panel_height',21.0)
rear_panel_z = param('rear_panel_z',17.0)
side_panel_length = param('side_panel_length',66.0)
side_panel_height = param('side_panel_height',13.0)
side_panel_y = param('side_panel_y',6.0)
side_panel_z = param('side_panel_z',13.0)
charge_width = param('charge_width',12.0)
charge_height = param('charge_height',5.0)
charge_z = param('charge_z',12.0)
outer = Pos(0,0,shell_lower_z)*extrude(RectangleRounded(case_width,case_depth,case_corner),amount=60)
clip = Pos(0,0,case_top_center)*Rot(case_slope,0,0)*Pos(0,0,-100)*Box(300,300,200)
outer = outer & clip
slope=math.tan(math.radians(case_slope))
top_edges=[e for e in outer.edges() if all(abs(v.Z-case_top_center-v.Y*slope)<0.001 for v in e.vertices())]
outer=fillet(top_edges,shell_edge_radius)
inner = extrude(RectangleRounded(case_width-2*shell_wall,case_depth-2*shell_wall,case_corner-shell_wall),amount=70)
inner_clip=Pos(0,0,case_top_center-shell_wall/math.cos(math.radians(case_slope)))*Rot(case_slope,0,0)*Pos(0,0,-100)*Box(300,300,200)
body=outer-(inner & inner_clip)
window=Pos(0,0,case_top_center)*Rot(case_slope,0,0)*Pos(0,fascia_y,-12)*extrude(RectangleRounded(fascia_width+2*panel_gap,fascia_depth+2*panel_gap,fascia_radius+panel_gap),amount=24)
body-=window
body-=Pos(0,0,case_top_center)*Rot(case_slope,0,0)*Pos(button_x,button_y,0)*Cylinder(button_diameter/2+panel_gap,24)
rear_cut=Pos(0,case_depth/2,rear_panel_z)*extrude(Plane.XZ*RectangleRounded(rear_panel_width+2*panel_gap,rear_panel_height+2*panel_gap,2.0),amount=12,both=True)
side_cut=Pos(case_width/2,side_panel_y,side_panel_z)*extrude(Plane.YZ*RectangleRounded(side_panel_length+2*panel_gap,side_panel_height+2*panel_gap,2.0),amount=12,both=True)
charge_cut=Pos(0,-case_depth/2,charge_z)*extrude(Plane.XZ*RectangleRounded(charge_width,charge_height,charge_height/2-0.01),amount=12,both=True)
body=body-rear_cut-side_cut-charge_cut
body.color=Color(0.88,0.86,0.79)
publish('shell',body,'Ivory main shell')